import {
  dark,
  font,
  highContrast,
  light,
  motion,
  radius,
  space,
  type,
  type Palette,
} from './tokens.js';

const kebab = (key: string) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function colorVars(palette: Palette, indent: string): string {
  return Object.entries(palette)
    .map(([key, value]) => `${indent}--cairn-color-${kebab(key)}: ${value};`)
    .join('\n');
}

/** Builds the CSS custom properties for both themes. Dark follows the system unless overridden. */
export function buildCss(): string {
  const shared = [
    ...Object.entries(radius).map(([k, v]) => `  --cairn-radius-${k}: ${v}px;`),
    ...Object.entries(space).map(([k, v]) => `  --cairn-space-${k}: ${v}px;`),
    ...Object.entries(type).flatMap(([k, v]) => [
      `  --cairn-text-${k}: ${v.size}px;`,
      `  --cairn-leading-${k}: ${v.line}px;`,
    ]),
    `  --cairn-font-sans: ${font.sans};`,
    `  --cairn-font-mono: ${font.mono};`,
    `  --cairn-duration-instant: ${motion.instant}ms;`,
    `  --cairn-duration-quick: ${motion.quick}ms;`,
    `  --cairn-duration-base: ${motion.base}ms;`,
    `  --cairn-duration-slow: ${motion.slow}ms;`,
    `  --cairn-ease: ${motion.ease};`,
  ].join('\n');

  return `/* Generated by packages/tokens. Do not edit; change src/tokens.ts. */
:root {
  color-scheme: light dark;
${colorVars(light, '  ')}
${shared}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${colorVars(dark, '    ')}
  }
}

:root[data-theme='dark'] {
${colorVars(dark, '  ')}
}

@media (prefers-contrast: more) {
  :root:not([data-theme]) {
    color-scheme: dark;
${colorVars(highContrast, '    ')}
  }
}

:root[data-theme='high-contrast'] {
  color-scheme: dark;
${colorVars(highContrast, '  ')}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --cairn-duration-instant: 1ms;
    --cairn-duration-quick: 1ms;
    --cairn-duration-base: 1ms;
    --cairn-duration-slow: 1ms;
  }
}
`;
}
